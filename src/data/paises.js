// País por defecto: España
export const PAIS_DEFAULT = PAISES.find((p) => p.codigo === "ES");

// Buscar país por código
export function getPais(codigo) {
  return PAISES.find((p) => p.codigo === codigo) || PAIS_DEFAULT;
}

// Validar número según país
export function validarTelefono(numero, codigoPais) {
  const pais = getPais(codigoPais);
  if (!pais.regex.test(limpiarNumero(numero))) {
    return {
      valido: false,
      mensaje: `El número no es válido para ${pais.nombre}. Formato esperado: ${pais.ejemplo} (${pais.longitud} dígitos)`,
    };
  }
  return { valido: true, mensaje: "" };
}

// Limpiar número (quitar espacios y guiones)
export function limpiarNumero(numero) {
  return numero.replace(/[\s\-().]/g, "");
}
